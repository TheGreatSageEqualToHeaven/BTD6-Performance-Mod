public sealed class InactiveBuffContract : NativeContract
{
    public GuardedCallSiteContract.Helper[] Helpers { get; set; } = Array.Empty<GuardedCallSiteContract.Helper>();
    public long Start { get; set; }
    public string Body { get; set; } = "";

    public void Verify(Func<long, int, byte[]> read)
    {
        new GuardedCallSiteContract
        {
            Helpers = Helpers
        }.Verify(read);
        var expected = Convert.FromHexString(Body);
        if (Start != 0xB2824B || expected.Length != 0x52 ||
            !read(Start, expected.Length).AsSpan().SequenceEqual(expected) ||
            !expected.AsSpan(0, 4).SequenceEqual(Convert.FromHexString("498B5500")) || expected[0x26] != 0xE8 ||
            Start + 0x2B + BitConverter.ToInt32(expected, 0x27) != 0xD71BF0 ||
            !expected.AsSpan(0x1B, 2).SequenceEqual(Convert.FromHexString("0F84")) ||
            Start + 0x21 + BitConverter.ToInt32(expected, 0x1D) != 0xB28D7C)
        {
            throw new InvalidOperationException(Errors.InactiveBuffInstructionBlockContinuationsChanged);
        }
    }
}

public sealed class GridPositionContract : NativeContract
{
    public GuardedCallSiteContract.Helper[] Helpers { get; set; } = Array.Empty<GuardedCallSiteContract.Helper>();
    public Block[] Blocks { get; set; } = Array.Empty<Block>();

    public void Verify(Func<long, int, byte[]> read)
    {
        if (Blocks.Length != 3 ||
            !Blocks.Select(b => b.Start).SequenceEqual(new long[] { 0xDAC5D8, 0xDAC68D, 0xDAC72D }))
        {
            throw new InvalidOperationException(Errors.GridCoordinateSitesChanged);
        }

        if (Helpers.Length != 3 ||
            !Helpers.Select(h => h.Rva).SequenceEqual(new long[] { 0x21FA140, 0xD71EB0, 0x6FD470 }) || !Helpers
                .Select(h => Convert.FromHexString(h.Body).Length).SequenceEqual(new[] { 0x67, 6, 6 }))
        {
            throw new InvalidOperationException(Errors.GridPositionHelperContractChanged);
        }

        new GuardedCallSiteContract
        {
            Helpers = Helpers
        }.Verify(read);
        foreach (var b in Blocks)
        {
            var expected = Convert.FromHexString(b.Body);
            if (expected.Length != 0x43 || !read(b.Start, expected.Length).AsSpan().SequenceEqual(expected))
            {
                throw new InvalidOperationException(Errors.GridPositionCallerChanged);
            }

            foreach (var (offset, target)in new[]
                     {
                         (0x1b, 0xD71EB0L),
                         (0x3e, 0x6FD470L)
                     }
                    )
            {
                if (expected[offset] != 0xe8 ||
                    b.Start + offset + 5 + BitConverter.ToInt32(expected, offset + 1) != target)
                {
                    throw new InvalidOperationException(Errors.GridPositionCoordinateCalleeChanged);
                }
            }
        }
    }

    public sealed class Block
    {
        public long Start { get; set; }
        public string Body { get; set; } = "";
    }
}

