public sealed class GuardedCallSiteContract : NativeContract
{
    public Helper[] Helpers { get; set; } = Array.Empty<Helper>();
    public Site[] Sites { get; set; } = Array.Empty<Site>();

    public void Verify(Func<long, int, byte[]> read)
    {
        foreach (var helper in Helpers)
        {
            VerifyBytes(read, helper.Rva, helper.Body);
        }

        foreach (var site in Sites)
        {
            VerifyBytes(read, site.ContextStart, site.Context);
            var bytes = Convert.FromHexString(site.Context);
            var offset = checked((int)(site.Rva - site.ContextStart));
            if (offset < 0 || offset > bytes.Length - 5 || bytes[offset] != (site.TailJump ? 0xE9 : 0xE8) ||
                site.Rva + 5 + BitConverter.ToInt32(bytes, offset + 1) != site.Callee)
            {
                throw new InvalidOperationException(Errors.UnexpectedCallSiteDestination);
            }

            if (site.Replacement.Length != 0 && Convert.FromHexString(site.Replacement).Length != 5)
            {
                throw new InvalidOperationException(Errors.InvalidCallSiteReplacementLength);
            }

            _ = Convert.FromHexString(site.ArgumentSetup);
        }
    }

    private static void VerifyBytes(Func<long, int, byte[]> read, long rva, string hex)
    {
        var expected = Convert.FromHexString(hex);
        if (expected.Length == 0 || !read(rva, expected.Length).AsSpan().SequenceEqual(expected))
        {
            throw new InvalidOperationException(Errors.NativeCallerHelperChangedAt + rva.ToString("X"));
        }
    }

    public sealed class Helper
    {
        public string Name { get; set; } = "";
        public long Rva { get; set; }
        public string Body { get; set; } = "";
    }

    public sealed class Site
    {
        public long Rva { get; set; }
        public long Callee { get; set; }
        public long ContextStart { get; set; }
        public string Context { get; set; } = "";
        public string Export { get; set; } = "";
        public string ArgumentSetup { get; set; } = "";
        public string Replacement { get; set; } = "";
        public bool TailJump { get; set; }
    }
}

public static class PatchSignature
{
    public static bool Matches(MethodInfo method, string declaringType, string name, string elementType)
    {
        return method.DeclaringType?.FullName == declaringType && method.Name == name &&
               method is { IsStatic: false, IsAbstract: false, ContainsGenericParameters: false } &&
               method.GetParameters().Length == 0 && method.ReturnType.IsGenericType &&
               method.ReturnType.GetGenericTypeDefinition().FullName ==
               "Il2CppSystem.Collections.Generic.IEnumerable`1" &&
               method.ReturnType.GetGenericArguments()[0].FullName == elementType;
    }
}

